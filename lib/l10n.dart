/// Seçili dildeki metin; anahtar yoksa Türkçeye, o da yoksa anahtarın kendisine düşer.
String tr(String key) {
  final lang = Game.instance.lang;
  return strings[lang]?[key] ?? strings['TR']![key] ?? key;
}

/// Zorluk düzeyinin yerelleştirilmiş adı (dosyalardaki anahtar: KOLAY, ORTA, ZOR).
String levelName(String level) => tr(switch (level) {
      'KOLAY' => 'easy',
      'ZOR' => 'hard',
      _ => 'normal',
    });
